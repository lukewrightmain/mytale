// ─── Helper Functions ───

function extractFileName(path: string): string {
  const parts = path.split('/');
  return parts[parts.length - 1];
}

function collectBindingElements(element: UIElement): { name: string; type: string; binding: Binding }[] {
  const results: { name: string; type: string; binding: Binding }[] = [];
  
  if (element.name) {
    const props = element.properties;
    if ('binding' in props && props.binding?.enabled) {
      results.push({
        name: element.name,
        type: element.type,
        binding: props.binding,
      });
    }
  }
  
  for (const child of element.children) {
    results.push(...collectBindingElements(child));
  }
  
  return results;
}

function generateEventBindings(elements: { name: string; type: string; binding: Binding }[]): string {
  if (elements.length === 0) {
    return `        // Add event bindings here
        // Example:
        // events.addEventBinding(
        //     CustomUIEventBindingType.Activating,  // Click event
        //     "#MyButton",                          // Element selector
        //     EventData.of("action", "buttonClick"),// Data to send
        //     false                                 // Not buffered
        // );`;
  }
  
  const lines: string[] = ['        // Event bindings'];
  for (const el of elements) {
    const eventType = el.binding.eventType || 'Activating';
    const actionName = el.binding.eventHandler || `on${el.name}Click`;
    lines.push(`        events.addEventBinding(`);
    lines.push(`            CustomUIEventBindingType.${eventType},`);
    lines.push(`            "#${el.name}",`);
    lines.push(`            EventData.of("action", "${actionName}").append("elementId", "${el.name}"),`);
    lines.push(`            false`);
    lines.push(`        );`);
    lines.push('');
  }
  
  return lines.join('\n');
}

function generateEventHandlers(elements: { name: string; type: string; binding: Binding }[]): string {
  if (elements.length === 0) {
    return `            case "exampleAction":
                // Handle example action
                break;`;
  }
  
  const lines: string[] = [];
  for (const el of elements) {
    const actionName = el.binding.eventHandler || `on${el.name}Click`;
    lines.push(`            case "${actionName}":`);
    lines.push(`                // Handle ${el.name} ${el.binding.eventType || 'click'}`);
    lines.push(`                System.out.println("${el.name} activated");`);
    lines.push(`                break;`);
  }
  
  return lines.join('\n');
}

function generateSelectorComments(elements: { name: string; type: string; path: string }[]): string {
  if (elements.length === 0) return '';
  
  const lines: string[] = [
    '        // ─── Available Selectors ───',
    '        // Use these selectors with ui.set() to update element properties:',
  ];
  
  for (const el of elements) {
    let props = '';
    switch (el.type) {
      case 'Label':
      case 'Title':
        props = '.Text, .Visible';
        break;
      case 'ItemIcon':
        props = '.ItemId, .Visible';
        break;
      case 'ProgressBar':
        props = '.Value';
        break;
      case 'AssetImage':
        props = '.Asset, .Visible';
        break;
      default:
        props = '.Visible';
    }
    lines.push(`        // ui.set("${el.path}${props}", value);`);
  }
  
  return lines.join('\n');
}

function generateHudSetters(elements: { name: string; type: string; path: string }[]): string {
  const lines: string[] = ['        // Set HUD content'];
  
  for (const el of elements) {
    if (el.type === 'Label') {
      if (el.name.toLowerCase().includes('main') || el.name.toLowerCase().includes('title')) {
        lines.push(`        ui.set("${el.path}.Text", mainText);`);
      } else if (el.name.toLowerCase().includes('sub')) {
        lines.push(`        ui.set("${el.path}.Text", subText);`);
      }
    }
  }
  
  if (lines.length === 1) {
    lines.push(`        // ui.set("#MainText.Text", mainText);`);
    lines.push(`        // ui.set("#SubText.Text", subText);`);
  }
  
  return lines.join('\n');
}

