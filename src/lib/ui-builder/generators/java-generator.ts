import type { UIDesign, UIElement, Binding } from '../types';

// ─── Generate Java Code ───
export function generateJavaCode(design: UIDesign): string {
  const { settings } = design;
  const isInteractive = settings.pageType === 'InteractiveCustomUIPage' || hasEventBindings(design.root);
  const isHud = settings.pageType === 'CustomUIHud';
  
  if (isHud) {
    return generateHudClass(design);
  } else if (isInteractive) {
    return generateInteractivePageClass(design);
  } else {
    return generateSimplePageClass(design);
  }
}

// ─── Check if design has event bindings ───
function hasEventBindings(element: UIElement): boolean {
  const props = element.properties;
  if ('binding' in props && props.binding?.enabled) return true;
  return element.children.some(hasEventBindings);
}

// ─── Collect elements with IDs (for selectors) ───
function collectNamedElements(element: UIElement, path: string = ''): { id: string; name: string; type: string; path: string }[] {
  const results: { id: string; name: string; type: string; path: string }[] = [];
  
  if (element.name) {
    const currentPath = path ? `${path} #${element.name}` : `#${element.name}`;
    results.push({
      id: element.id,
      name: element.name,
      type: element.type,
      path: currentPath,
    });
    
    for (const child of element.children) {
      results.push(...collectNamedElements(child, currentPath));
    }
  } else {
    for (const child of element.children) {
      results.push(...collectNamedElements(child, path));
    }
  }
  
  return results;
}

